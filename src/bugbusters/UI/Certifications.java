    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int row = tblCertifications.getSelectedRow();
        
        if(row == -1){
            JOptionPane.showMessageDialog(this, "Select a record to first!", "CERTIFICATION RECORD", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        try{int certID = Integer.parseInt(textCertID.getText().trim());
            Connection con = BBConnection.MSAccessConnection();
            String sql = "UPDATE Certifications SET techCert=?, techSpec=? " + "WHERE certID=?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, textCert.getText());
            pst.setString(2, textSpec.getText());
            pst.setInt(3, certID);
            pst.executeUpdate();
            
            con.close();
            loadCertToTable();
            clearFields();
            
        }catch(Exception e){
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = tblCertifications.getSelectedRow();
        
        if(row == -1){
            JOptionPane.showMessageDialog(this, "Please Select a record to delete!", "CERTIFICATIONS RECORD", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this record?","Confirm Delete", JOptionPane.YES_NO_OPTION);
        if(confirm != JOptionPane.YES_OPTION){
            return;
        }
        
        try{
            Connection con = BBConnection.MSAccessConnection();
            con.setAutoCommit(false);
            
            String sql = "DELETE FROM Certifications WHERE certID=?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, textCertID.getText());
            pst.executeUpdate();
            
            con.commit();
            JOptionPane.showMessageDialog(this, "Record Deleted Successfully!", "CERTIFICATION RECORD", JOptionPane.INFORMATION_MESSAGE);
            loadCertToTable();
            clearFields();
        }catch(SQLException e){
            System.out.println(e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        try{
            if(!isFormValid()){
              JOptionPane.showMessageDialog(this, "Please fill up all the fields!", "CERTIFICATION RECORD", JOptionPane.INFORMATION_MESSAGE);  
              return;
            }
            Connection con = BBConnection.MSAccessConnection();
            
            String techCert = textCert.getText().trim();
            String techSpec = textSpec.getText().trim();
            
            String sql = "INSERT INTO Certifications (techID, techCert, techSpec)" + "VALUES (?,?,?)";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, this.techID);
            pst.setString(2, techCert);
            pst.setString(3, techSpec);
            pst.executeUpdate();
            
            con.commit();
            loadCertToTable();
            clearFields();
            JOptionPane.showMessageDialog(this, "Certifications Added!", "CERTIFICATION RECORD", JOptionPane.INFORMATION_MESSAGE);  
        } catch(Exception e){
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_btnAddActionPerformed

