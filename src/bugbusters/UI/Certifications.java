    private boolean isFormValid(){
        if(textCert.getText().trim().isEmpty()) return false;
        if(textSpec.getText().trim().isEmpty()) return false;
        
        return true;
    }
    
    private void clearFields(){
        textCert.setText("");
        textSpec.setText("");
        textCertID.setText("");
    }
    private void fillFieldsFromSelectedRow(){
        int row = tblCertifications.getSelectedRow();
        if(row == -1) return;
        
        //GETTING THE VALIES FROM THE TABLE
        String certID = tblCertifications.getValueAt(row, 0).toString().trim();
        String techID = tblCertifications.getValueAt(row, 1).toString();
        String cert = tblCertifications.getValueAt(row, 2).toString();
        String spec = tblCertifications.getValueAt(row, 3).toString();
        
        //UPDATING THE CERTIFICATION CLASS
        this.cert.setCertID(Integer.parseInt(certID));
        this.cert.setTechID(techID);
        this.cert.setTechCert(cert);
        this.cert.setTechSpec(spec);
        
        //SETTING THE VALUES IN THE FIELDS
        textCertID.setText(certID);
        textCert.setText(cert);
        textSpec.setText(spec);
    }
    
    private void loadCertToTable (){
        Connection con = BBConnection.MSAccessConnection();
        try{
        DefaultTableModel model = (DefaultTableModel)tblCertifications.getModel();
        model.setRowCount(0);
        
        String sql = "SELECT certID, techID, techCert, techSpec FROM Certifications WHERE techID = ?";
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, this.techID);
        ResultSet rs = pst.executeQuery();
        
        while (rs.next()){
            model.addRow(new Object[]{
                rs.getInt("certID"),
                rs.getString("techID"),
                rs.getString("techCert"),
                rs.getString("techSpec")
            });
        }
        }catch(SQLException e){
            System.out.println(e.getMessage());
        }
    }
    
    
