    // ENSURES TO LOAD/UPDATE THE TABLE IN GUI IF THERE'S DATA
    private void loadTechToTable(){
        Connection con = BBConnection.MSAccessConnection();
        try{
            DefaultTableModel model = (DefaultTableModel)tblTechnician.getModel();
            model.setRowCount(0);
            
            String sql = "SELECT t.techID, t.lastName, t.firstName, t.contactNum " +
                        "FROM TechnicianDetails AS t ORDER BY techID";
            PreparedStatement pst = con.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();
            
            while(rs.next()){
                model.addRow(new Object[]{
                    rs.getString("techID"),
                    rs.getString("lastName"),
                    rs.getString("firstName"),
                    rs.getString("contactNum")
                });
            }
        } catch (Exception e){
            System.out.println(e.getMessage());
        }
    }
      
