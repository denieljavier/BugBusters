    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = tblTechnician.getSelectedRow();
        
        if(row == -1){
            JOptionPane.showMessageDialog(this, "Please Select a record to delete!", "TECHNICIAN RECORD", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this record?","Confirm Delete", JOptionPane.YES_NO_OPTION);
        if(confirm != JOptionPane.YES_OPTION){
            return;
        }
        
        try{
            Connection con = BBConnection.MSAccessConnection();
            con.setAutoCommit(false);
            
//            int certID = (int) tblTechnician.getValueAt(row, 6);
            
            // DELETE CERT
            String sqlCert = "DELETE FROM Certifications WHERE techID = ?";
            PreparedStatement pstCert = con.prepareStatement(sqlCert);
            pstCert.setString(1, textTechID.getText());
            pstCert.executeUpdate();
            
            // DELETE TECH-ASSIGN
            String sqlTechAss = "DELETE FROM TechAssign WHERE techID = ?";
            PreparedStatement pstTechAss = con.prepareStatement(sqlTechAss);
            pstTechAss.setString(1, textTechID.getText());
            pstTechAss.executeUpdate();
            
            // DELETE TECH-SOLUTION
            String sqlSol = "DELETE FROM TechSolutionCarry WHERE techID = ?";
            PreparedStatement pstSol = con.prepareStatement(sqlSol);
            pstSol.setString(1, textTechID.getText());
            pstSol.executeUpdate();
            
            // DELETE TECHNICIAN
            String sqlTech = "DELETE FROM TechnicianDetails WHERE techID = ?";
            PreparedStatement pstTech = con.prepareStatement(sqlTech);
            pstTech.setString(1, textTechID.getText());
            pstTech.executeUpdate();
            
            con.commit();
            JOptionPane.showMessageDialog(this, "Record Deleted Successfully!", "TECHNICIAN RECORD", JOptionPane.INFORMATION_MESSAGE);
            loadTechToTable();
            clearFields();
            
        } catch(SQLException e){
            System.out.println(e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed
    // SEARCH BUTTON
    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        DefaultTableModel model = (DefaultTableModel)tblTechnician.getModel();
        model.setRowCount(0); // Clearing the Table
        
        String search = textSearch.getText().trim();
        
        if (search.isEmpty()){
             loadTechToTable();
             return;
        }
        
        try{
            String sql = "SELECT t.techID, t.firstName, t.lastName, t.contactNum " +
                    "From TechnicianDetails AS t " +
                    "WHERE UCASE(t.techID) = ?" +
                    "ORDER BY t.techID";
            
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, search.toUpperCase());
            ResultSet rs = pst.executeQuery();
            
            if(rs.next()){
                model.addRow(new Object[]{
                    rs.getString("techID"),
                    rs.getString("firstName"),
                    rs.getString("lastName"),
                    rs.getString("contactNum")
                });
            } else{
             JOptionPane.showMessageDialog(this, "No Record Found!", "Error 404", JOptionPane.WARNING_MESSAGE);   
            }
            
        }catch(Exception e){
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_btnSearchActionPerformed

