    private void btnDeleteSolActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteSolActionPerformed
        Connection con = BBConnection.MSAccessConnection();
        
        int row = tblSolution.getSelectedRow();
        
        if(row == -1){
            JOptionPane.showMessageDialog(this, "Please Select a record to delete!", "SOLUTION RECORD", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this record?","Confirm Delete", JOptionPane.YES_NO_OPTION);
        if(confirm != JOptionPane.YES_NO_OPTION){
            return;
        }
        
        Object value = tblSolution.getValueAt(row, 0);
        int solutionID = Integer.parseInt(value.toString());
        
        try{
            con.setAutoCommit(false);
        //DELETING JOB SOLUTION
        try(PreparedStatement pst1 = con.prepareStatement(
        "DELETE FROM JobSolution WHERE solutionID = ?")){
            pst1.setInt(1, solutionID);
            pst1.executeUpdate();
        }
        //DELETING TECH SOLUTION CARRY
        try(PreparedStatement pst2 = con.prepareStatement(
        "DELETE FROM TechSolutionCarry WHERE solutionID = ?")){
            pst2.setInt(1, solutionID);
            pst2.executeUpdate();
        }
        //DELETING SOLUTION
        try(PreparedStatement pst3 = con.prepareStatement(
        "DELETE FROM Solutions WHERE solutionID = ?")){
            pst3.setInt(1, solutionID);
            pst3.executeUpdate();
        }
        
        con.commit();
        loadSolutionToTable();
        loadUsedSolToTable();
        clearFields();
        JOptionPane.showMessageDialog(this, "Record Deleted Successfully!", "SOLUTION RECORD", JOptionPane.INFORMATION_MESSAGE);
        } catch (SQLException e){
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_btnDeleteSolActionPerformed

