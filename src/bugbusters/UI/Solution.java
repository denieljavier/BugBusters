     private void loadUsedSolToTable(){
            String sql = "SELECT js.jobID, j.jobDate, ta.techID, s.solutionName " +
                    "FROM ((JobSolution AS js " +
                    "INNER JOIN Job AS j ON js.jobID = j.jobID) " +
                    "INNER JOIN TechAssign AS ta ON js.jobID = ta.jobID) " +
                    "INNER JOIN Solutions AS s ON js.solutionID = s.solutionID " +
                    "WHERE ta.status = 'DONE' OR ta.status = 'PENDING'" +
                    "ORDER BY j.jobDate";
            try{
            DefaultTableModel model = (DefaultTableModel)tblUsedSol.getModel();
            model.setRowCount(0);
            Connection con = BBConnection.MSAccessConnection();
            PreparedStatement pstSol = con.prepareStatement(sql);
            ResultSet rs = pstSol.executeQuery();
            
            while(rs.next()){
                model.addRow(new Object[]{
                    rs.getInt("jobID"),
                    rs.getDate("jobDate"),
                    rs.getString("techID"),
                    rs.getString("solutionName")
                });
            
            } 
            
        }catch (SQLException e){
                System.out.println(e.getMessage());
            }
     }
     
    private void loadSolutionToTable(){
        try{
            DefaultTableModel model = (DefaultTableModel)tblSolution.getModel();
            model.setRowCount(0);
            Connection con = BBConnection.MSAccessConnection();
         
            String sql = 
                    "SELECT s.solutionID, s.solutionName " +
                    "FROM Solutions AS s " +
                    "LEFT JOIN JobSolution AS js ON s.solutionID = js.solutionID " +
                    "LEFT JOIN TechAssign AS ta ON js.jobID = ta.jobID " +
                    "WHERE ta.status IS NULL OR ta.status = ''";
            PreparedStatement pstSol = con.prepareStatement(sql);
            ResultSet rs = pstSol.executeQuery();
            
            while(rs.next()){
                model.addRow(new Object[]{
                    rs.getString("solutionID"),
                    rs.getString("solutionName")
                });
            }
                
        } catch(Exception e){
            System.out.println(e.getMessage());
        }
    }
  
